/**
 * Результат операции с картой (пополнение, оплата, погашение долга).
 *
 * enum - тип с заранее известным набором значений. Метод возвращает одно из них,
 * а печатает сообщение тот, кто метод вызвал (Main). Так классы карт ничего не выводят
 * сами и их легко проверять в тестах.
 *
 * Неправильные аргументы (сумма <= 0) - это ошибка программиста, который вызвал метод,
 * для них бросается исключение IllegalArgumentException. А отказ банка (карта заблокирована,
 * не хватает денег) - обычная ситуация, для нее - значение этого enum.
 */
public enum OperationResult {
    OK,                 // операция выполнена
    CARD_BLOCKED,       // карта заблокирована - операции запрещены
    CARD_EXPIRED,       // срок действия карты закончился
    NOT_ENOUGH_MONEY,   // не хватает денег (своих, а у кредитной карты - и кредитных)
    NO_DEBT             // погашать нечего: долга нет (только у кредитной карты)
}
