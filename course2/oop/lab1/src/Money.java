import java.util.Locale;

/**
 * Вспомогательный класс: деньги в программе хранятся в копейках (целое число long).
 *
 * Почему не double: double хранит число в двоичном виде, и многие десятичные дроби
 * в нем записываются неточно (0.1 + 0.2 = 0.30000000000000004). Для денег это ошибка.
 * Целое число копеек складывается и вычитается точно: 15000 руб. 50 коп. = 1500050.
 *
 * В коде суммы удобно писать с подчеркиванием перед копейками: 15000_50 = 15000.50.
 * Java разрешает "_" внутри числа, на значение он не влияет.
 *
 * Класс не входит в иерархию из задания: это просто набор функций (как Math).
 */
public final class Money {

    // объекты этого класса не нужны: все методы статические, поэтому конструктор закрыт
    private Money() {
    }

    /**
     * Копейки -> текст "рубли.копейки" с двумя цифрами после точки: 1500050 -> "15000.50".
     * String.format("%.2f") здесь не подходит: на Windows с русским языком
     * он печатает запятую ("15000,50"), а нам нужен одинаковый вывод на любом компьютере.
     */
    public static String format(long cents) {
        // знак отдельно: у -150 копеек и рубли, и копейки должны печататься без минуса
        String sign = cents < 0 ? "-" : "";
        // деление и остаток берем до Math.abs, чтобы не было переполнения у Long.MIN_VALUE
        long rubles = Math.abs(cents / 100);
        long kopecks = Math.abs(cents % 100);
        // Locale.ROOT - формат без национальных особенностей; %02d - две цифры: 5 -> "05"
        return String.format(Locale.ROOT, "%s%d.%02d", sign, rubles, kopecks);
    }
}
